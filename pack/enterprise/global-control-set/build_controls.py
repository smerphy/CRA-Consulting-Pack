def build():
    reqs, maps = [], []
    for i, (group, title, summary, evidence, m, strictest) in enumerate(G, start=1):
        rid = f"UCS-{i:02d}"
        assert set(m) == set(ABBR), (rid, set(ABBR) ^ set(m))
        reqs.append({"id": rid, "group": group, "ref": rid, "title": title, "summary": summary,
                     "evidence": evidence, "strictest": strictest})
        for ab, (cov, refs, note) in m.items():
            maps.append({"req": rid, "fw": ABBR[ab], "refs": refs, "coverage": COV[cov], "note": note,
                         "source": "kb" if ab == "cra" else "web"})
