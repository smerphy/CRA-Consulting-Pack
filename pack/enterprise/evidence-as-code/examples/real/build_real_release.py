def sha(path, alg="sha256"):
    h = hashlib.new(alg)
    with open(path, "rb") as fh:
        h.update(fh.read())
    return h.hexdigest()


def fetch(url, dst, data=None):
    req = urllib.request.Request(url, data=data, headers={"User-Agent": "cra-evidence-proof/1.1"})
    with urllib.request.urlopen(req, timeout=60) as r, open(dst, "wb") as fh:
        fh.write(r.read())


def download(sources):
    os.makedirs(os.path.join(REL, "artefact"), exist_ok=True)
    os.makedirs(os.path.join(REL, "evidence"), exist_ok=True)
    os.makedirs(os.path.join(REL, "feeds"), exist_ok=True)
    when = _dt.datetime.now(_dt.timezone.utc).replace(microsecond=0).isoformat().replace("+00:00", "Z")
    for key, rel in (("tarball", "artefact/sigstore-5.0.0.tgz"), ("attestations", "evidence/npm-attestations.json"),
                     ("npm_keys", "npm-registry-keys.json")):
        fetch(URLS[key], os.path.join(REL, rel))
        sources[rel] = {"status": "real (downloaded unmodified)", "url": URLS[key], "retrieved": when}


def make_sbom(sources):
    """npm sbom over the real runtime dependency tree (no install scripts run)."""
    tmp = tempfile.mkdtemp(prefix="sbom-")
    try:
        with tarfile.open(os.path.join(REL, "artefact", "sigstore-5.0.0.tgz")) as tf:
            member = tf.getmember("package/package.json")
            pj = json.load(tf.extractfile(member))
        pj.pop("devDependencies", None)      # unpublished workspace dev packages; runtime tree only
        pj.pop("scripts", None)
        os.makedirs(os.path.join(tmp, "sigstore"))
        with open(os.path.join(tmp, "sigstore", "package.json"), "w") as fh:
            json.dump(pj, fh)
        cwd = os.path.join(tmp, "sigstore")
        subprocess.run(["npm", "install", "--package-lock-only", "--ignore-scripts", "--omit=dev", "--no-audit",
                        "--no-fund"], cwd=cwd, check=True, capture_output=True)
        out = subprocess.run(["npm", "sbom", "--sbom-format", "cyclonedx", "--omit", "dev", "--package-lock-only"],
                             cwd=cwd, check=True, capture_output=True, text=True).stdout
        npm_version = subprocess.run(["npm", "--version"], capture_output=True, text=True).stdout.strip()
    finally:
        shutil.rmtree(tmp, ignore_errors=True)
    bom = json.loads(out)
    art = os.path.join(REL, "artefact", "sigstore-5.0.0.tgz")
    comp = bom["metadata"]["component"]
    comp["name"] = PKG
    comp["hashes"] = [{"alg": "SHA-256", "content": sha(art)}, {"alg": "SHA-512", "content": sha(art, "sha512")}]
    with open(os.path.join(REL, "evidence", "sbom.cdx.json"), "w") as fh:
        json.dump(bom, fh, indent=2)
    sources["evidence/sbom.cdx.json"] = {
        "status": "generated by this module from real inputs",
        "method": "npm %s `npm sbom --sbom-format cyclonedx` over package.json runtime dependencies resolved "
                  "against registry.npmjs.org; root component renamed to the package and given the tarball "
                  "digests" % npm_version,
        "components": len(bom.get("components") or [])}
    return bom, pj


def osv(bom, sources, live):
    path = os.path.join(REL, "feeds", "osv-snapshot.json")
    if live:
        q = {"queries": [{"package": {"ecosystem": "npm", "name": c["name"]}, "version": c["version"]}
                         for c in bom["components"]]}
        tmp = path + ".q"
        fetch(URLS["osv_querybatch"], tmp, json.dumps(q).encode())
        res = json.load(open(tmp))
        os.remove(tmp)
        ids = sorted({v["id"] for r in res.get("results") or [] for v in r.get("vulns") or []})
        vulns = []
        for i in ids:
            fetch(URLS["osv_vuln"].format(id=i), tmp)
            vulns.append(json.load(open(tmp)))
            os.remove(tmp)
        with open(path, "w") as fh:
            json.dump({"vulns": vulns}, fh, indent=2)
        sources["feeds/osv-snapshot.json"] = {
            "status": "real (api.osv.dev querybatch + vulns, unmodified records)",
            "retrieved": _dt.datetime.now(_dt.timezone.utc).replace(microsecond=0).isoformat().replace("+00:00", "Z"),
            "ids": ids}
    return json.load(open(path))["vulns"]


def sast(eslint_dir, sources):
    # ESLint flat config only lints files under its base path, so work inside eslint_dir.
    tmp = tempfile.mkdtemp(prefix="sast-", dir=eslint_dir)
    try:
        with tarfile.open(os.path.join(REL, "artefact", "sigstore-5.0.0.tgz")) as tf:
            tf.extractall(tmp, filter="data")
        cfg = os.path.join(eslint_dir, "eslint.config.cjs")
        with open(cfg, "w") as fh:
            fh.write('const security = require("eslint-plugin-security");\n'
                     'module.exports = [{ files: ["**/*.js"], languageOptions: { ecmaVersion: "latest", '
                     'sourceType: "commonjs" }, plugins: { security }, rules: { ...security.configs.recommended'
                     '.rules, "no-eval": "error", "no-implied-eval": "error", "no-new-func": "error" } }];\n')
        out = os.path.join(tmp, "sast.sarif")
        subprocess.run([os.path.join(eslint_dir, "node_modules", ".bin", "eslint"), "-c", cfg, "--no-config-lookup",
                        "-f", "@microsoft/eslint-formatter-sarif", "-o", out, os.path.join(tmp, "package", "dist")],
                       cwd=eslint_dir, check=False, capture_output=True)
        text = open(out).read().replace("file://" + tmp + "/", "")
        doc = json.loads(text)
        for run in doc.get("runs") or []:
            for a in run.get("artifacts") or []:
                loc = a.get("location") or {}
                if "uri" in loc:
                    loc["uri"] = loc["uri"].replace("file://" + tmp + "/", "")
        with open(os.path.join(REL, "evidence", "sast.sarif"), "w") as fh:
            json.dump(doc, fh, indent=2)
        drv = doc["runs"][0]["tool"]["driver"]
        sources["evidence/sast.sarif"] = {
            "status": "generated by this module from the real artefact",
            "method": "%s %s with eslint-plugin-security recommended rules plus no-eval/no-implied-eval/"
                      "no-new-func over package/dist/*.js; SARIF via @microsoft/eslint-formatter-sarif" % (
                          drv.get("name"), drv.get("version")),
            "results": len(doc["runs"][0].get("results") or [])}
    finally:
        shutil.rmtree(tmp, ignore_errors=True)


def vex(vulns, art):
    statements = []
    for v in vulns:
        cve = next((a for a in v.get("aliases") or [] if a.startswith("CVE-")), v["id"])
        pkg = v["affected"][0]["package"]["name"]
        statements.append({
            "vulnerability": {"name": cve, "aliases": [v["id"]]},
            "products": [{"@id": "pkg:npm/sigstore@5.0.0", "subcomponents": [{"@id": "pkg:npm/%s" % pkg}]}],
            "status": "under_investigation",
            "status_notes": "Advisory published %s; reachability analysis pending (demonstration VEX, not an "
                            "assessment by the sigstore-js maintainers)" % v.get("published", "")[:10]})
    doc = {"@context": "https://openvex.dev/ns/v0.2.0",
           "@id": "https://vex.aldermoor.example/third-party/npm-sigstore/5.0.0",
           "author": "Aldermoor PSIRT (demonstration)", "role": "integrator",
           "timestamp": "2026-11-01T12:00:00Z", "version": 1, "statements": statements}
    with open(os.path.join(REL, "evidence", "vex.openvex.json"), "w") as fh:
        json.dump(doc, fh, indent=2)
    st = {"_type": "https://in-toto.io/Statement/v1",
          "subject": [{"name": "pkg:npm/sigstore@5.0.0", "digest": {"sha256": sha(art), "sha512": sha(art, "sha512")}}],
          "predicateType": MX.OPENVEX_PT, "predicate": doc}
    with open(os.path.join(REL, "evidence", "vex.openvex.intoto.json"), "w") as fh:
        json.dump(MX.sign(st, MX.PSIRT_KEY), fh, indent=2)


