def online_crosscheck():
    """Optional network checks, recorded beside the offline results.

    1. Fetch each Rekor entry by log index and compare its body with the
       canonicalized body carried in the bundle.
    2. Refresh the Sigstore public-good trusted root over TUF and compare it
       with the copy pinned in trust/.
    """
    out = {"checked": _dt.datetime.now(_dt.timezone.utc).replace(microsecond=0).isoformat().replace("+00:00", "Z")}
    atts = json.load(open(os.path.join(REL, "evidence", "npm-attestations.json")))["attestations"]
    out["rekor"] = []
    for a in atts:
        e = a["bundle"]["verificationMaterial"]["tlogEntries"][0]
        tmp = os.path.join(tempfile.mkdtemp(), "e.json")
        try:
            fetch("https://rekor.sigstore.dev/api/v1/log/entries?logIndex=%s" % e["logIndex"], tmp)
            live = next(iter(json.load(open(tmp)).values()))
            out["rekor"].append({"predicateType": a["predicateType"], "logIndex": e["logIndex"],
                                 "body_matches_bundle": live.get("body") == e["canonicalizedBody"],
                                 "integratedTime_matches": str(live.get("integratedTime")) == str(e["integratedTime"])})
        except Exception as ex:  # noqa: BLE001
            out["rekor"].append({"logIndex": e["logIndex"], "error": str(ex)})
    try:
        from sigstore.models import ClientTrustConfig
        cfg = ClientTrustConfig.production(offline=False)
        live_root = json.loads(cfg.trusted_root._inner.to_json())
        pinned = json.load(open(os.path.join(ROOT, "trust", "sigstore-public-good.trusted_root.json")))
        keyset = lambda r: sorted(t["logId"]["keyId"] for t in r.get("tlogs") or [])  # noqa: E731
        out["tuf"] = {"refreshed": True, "same_rekor_log_ids": keyset(live_root) == keyset(pinned),
                      "same_fulcio_cas": len(live_root.get("certificateAuthorities") or []) ==
                      len(pinned.get("certificateAuthorities") or [])}
    except Exception as ex:  # noqa: BLE001
        out["tuf"] = {"refreshed": False, "error": str(ex)}
    MX.write(os.path.join(REL, "online-crosscheck.json"), out)
    return out


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--download", action="store_true", help="re-download real inputs (network)")
    ap.add_argument("--online-check", action="store_true", help="cross-check Rekor entries and TUF root online")
    ap.add_argument("--eslint-dir", help="directory with eslint + plugins installed; regenerates sast.sarif")
    args = ap.parse_args(argv)
    src_path = os.path.join(REL, "sources.json")
    sources = json.load(open(src_path)) if os.path.exists(src_path) else {}
    if args.download or not os.path.exists(os.path.join(REL, "artefact", "sigstore-5.0.0.tgz")):
        download(sources)
    art = os.path.join(REL, "artefact", "sigstore-5.0.0.tgz")
    if args.download or not os.path.exists(os.path.join(REL, "evidence", "sbom.cdx.json")):
        bom, pj = make_sbom(sources)
    else:
        bom = json.load(open(os.path.join(REL, "evidence", "sbom.cdx.json")))
        with tarfile.open(art) as tf:
            pj = json.load(tf.extractfile("package/package.json"))
    vulns = osv(bom, sources, live=args.download or not os.path.exists(os.path.join(REL, "feeds", "osv-snapshot.json")))
    if args.eslint_dir:
        sast(os.path.abspath(args.eslint_dir), sources)
    os.makedirs(os.path.join(REL, "feeds"), exist_ok=True)
    shutil.copy(os.path.join(ROOT, "examples", "feeds", "kev-snapshot.json"), os.path.join(REL, "feeds", "kev-snapshot.json"))
    vex(vulns, art)
    docs()
    manifest(pj)
    policy()
    for rel in ("artefact/sigstore-5.0.0.tgz", "evidence/npm-attestations.json", "npm-registry-keys.json",
                "evidence/sbom.cdx.json", "feeds/osv-snapshot.json", "evidence/sast.sarif"):
        sources.setdefault(rel, {})["sha256"] = sha(os.path.join(REL, rel))
    sources["evidence/vex.openvex.json"] = {"status": "synthetic (authored for the demonstration)"}
    sources["release.json"] = {"status": "synthetic CRA metadata around a real artefact"}
    sources["feeds/kev-snapshot.json"] = {"status": "illustrative excerpt (copied from examples/feeds)"}
    MX.write(src_path, sources)
    if args.online_check:
        print(json.dumps(online_crosscheck(), indent=2))
    print("real-artefact release written under", REL)


if __name__ == "__main__":
    main()
